#!/usr/bin/env python3
"""Run a synthetic-only Scanpy demonstration; no downloads or study data.

This example is not a publication pipeline or a biological inference analysis.
Only the generated artificial ID scheme and approved simulation metadata are read.
"""
from __future__ import annotations

import argparse
import hashlib
from importlib.metadata import version
from pathlib import Path
import platform
import re

import anndata as ad
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import scanpy as sc
from scipy import io, sparse

from make_synthetic_data import ORIGIN, simulate


def validate_counts(matrix: sparse.spmatrix, *, integer: bool = True) -> sparse.csr_matrix:
    """Reject malformed, nonfinite, negative, or noninteger raw count inputs."""
    counts = sparse.csr_matrix(matrix)
    values = counts.data
    if counts.ndim != 2 or min(counts.shape) < 2:
        raise ValueError("Counts must be a two-dimensional cells × genes matrix.")
    if not np.all(np.isfinite(values)) or np.any(values < 0):
        raise ValueError("Counts must be finite and nonnegative.")
    if integer and not np.allclose(values, np.rint(values), rtol=0, atol=1e-8):
        raise ValueError("Raw counts must be integer-valued.")
    if np.any(np.asarray(counts.sum(axis=1)).ravel() == 0):
        raise ValueError("Every input cell must have at least one count.")
    return counts


def validate_ids(genes: pd.Index, barcodes: pd.Index) -> None:
    if not genes.is_unique or not barcodes.is_unique:
        raise ValueError("Gene and cell identifiers must be unique.")
    if not all(re.fullmatch(r"Gene\d{4,}", str(x)) for x in genes):
        raise ValueError("Only artificial Gene0001-style gene identifiers are accepted.")
    if not all(re.fullmatch(r"SIMCELL\d{4,}", str(x)) for x in barcodes):
        raise ValueError("Only artificial SIMCELL0001-style cell identifiers are accepted.")


def load_input(path: Path | None = None, input_dir: Path | None = None,
               seed: int = 7) -> tuple[ad.AnnData, str, str]:
    """Rebuild AnnData from whitelisted fields instead of carrying hidden metadata."""
    if path is not None and input_dir is not None:
        raise ValueError("Choose an h5ad file or a SoupX matrix directory, not both.")
    if input_dir is not None:
        directory = input_dir.expanduser().resolve(strict=True)
        provenance = pd.read_csv(directory / "run_metadata.tsv", sep="\t", dtype=str)
        metadata = dict(zip(provenance["key"], provenance["value"], strict=True))
        if metadata.get("data_origin") != ORIGIN:
            raise ValueError("SoupX input must carry the independent simulation provenance tag.")
        features = pd.read_csv(directory / "features.tsv", sep="\t", header=None, dtype=str)
        barcodes = pd.read_csv(directory / "barcodes.tsv", sep="\t", header=None, dtype=str)
        genes = pd.Index(features[0], name="gene_id")
        cells = pd.Index(barcodes[0], name="barcode")
        validate_ids(genes, cells)
        matrix = io.mmread(directory / "matrix.mtx", spmatrix=True).T.tocsr()
        if matrix.shape != (len(cells), len(genes)):
            raise ValueError("Matrix dimensions must match the barcode and feature tables.")
        counts = validate_counts(matrix, integer=False)
        data = ad.AnnData(counts, obs=pd.DataFrame(index=cells), var=pd.DataFrame(index=genes))
        metrics_path = directory / "cell_metrics.csv"
        if metrics_path.exists():
            metrics = pd.read_csv(metrics_path, index_col="barcode")
            if not metrics.index.is_unique or set(metrics.index) != set(cells):
                raise ValueError("Cell metadata must align one-to-one with the matrix barcodes.")
            for column, pattern in (("simulation_population", r"population_[123]"),
                                    ("simulation_batch", r"batch_[12]")):
                if column in metrics:
                    values = metrics.loc[cells, column].astype(str)
                    if not values.str.fullmatch(pattern).all():
                        raise ValueError("Unexpected simulation labels.")
                    data.obs[column] = pd.Categorical(values)
        data.var["is_qc_proxy"] = [int(x[4:]) <= 15 for x in genes]
        data.uns["data_origin"] = ORIGIN
        digest = hashlib.sha256((directory / "matrix.mtx").read_bytes()).hexdigest()
        return data, "soupx_adjusted_counts", digest
    source = sc.read_h5ad(path.expanduser().resolve(strict=True)) if path is not None else simulate(seed=seed)[0]
    if source.uns.get("data_origin") != ORIGIN:
        raise ValueError("Input must be generated by make_synthetic_data.py.")
    validate_ids(source.var_names, source.obs_names)
    counts = validate_counts(source.X)
    obs = pd.DataFrame(index=source.obs_names.copy())
    for column, pattern in (("simulation_population", r"population_[123]"),
                            ("simulation_batch", r"batch_[12]")):
        values = source.obs[column].astype(str)
        if not values.str.fullmatch(pattern).all():
            raise ValueError("Unexpected simulation labels.")
        obs[column] = pd.Categorical(values)
    # Drop all unrecognized layers, annotations, paths, embeddings, and uns fields.
    var = pd.DataFrame({"is_qc_proxy": [int(x[4:]) <= 15 for x in source.var_names]},
                       index=source.var_names.copy())
    data = ad.AnnData(counts, obs=obs, var=var)
    data.uns["data_origin"] = ORIGIN
    digest = hashlib.sha256(counts.data.tobytes() + counts.indices.tobytes() + counts.indptr.tobytes()).hexdigest()
    return data, "rawcounts", digest


def run(data: ad.AnnData, output: Path, *, seed: int = 7, count_layer: str = "rawcounts",
        input_hash: str = "in_memory", min_genes: int = 100, max_proxy_pct: float = 25,
        n_hvg: int = 300, resolution: float = 0.5) -> ad.AnnData:
    output = output.expanduser().resolve()
    if output.exists() and any(output.iterdir()):
        raise FileExistsError("Output directory must be empty; choose a new directory.")
    if min_genes < 1 or not 0 < max_proxy_pct <= 100 or n_hvg < 2 or resolution <= 0:
        raise ValueError("QC and clustering parameters must be positive and meaningful.")
    output.mkdir(parents=True, exist_ok=True)
    data = data.copy()
    cells_before = data.n_obs
    sc.pp.calculate_qc_metrics(data, qc_vars=["is_qc_proxy"], percent_top=None, log1p=False, inplace=True)
    keep = ((data.obs["n_genes_by_counts"] >= min_genes) &
            (data.obs["pct_counts_is_qc_proxy"] <= max_proxy_pct))
    qc = data.obs.copy()
    qc["passes_demo_qc"] = keep
    qc.to_csv(output / "synthetic_qc.csv", index_label="barcode")
    data = data[keep].copy()
    sc.pp.filter_genes(data, min_cells=3)
    if data.n_obs < 12 or data.n_vars < 10:
        raise ValueError("Too few cells or genes remain for this demonstration.")
    data.layers[count_layer] = data.X.copy()
    sc.pp.normalize_total(data, target_sum=1e4)
    sc.pp.log1p(data)
    # Seurat flavor expects log-normalized data. Counts stay in their own layer.
    sc.pp.highly_variable_genes(data, flavor="seurat", n_top_genes=min(n_hvg, data.n_vars))
    n_components = min(30, data.n_obs - 1, int(data.var["highly_variable"].sum()) - 1)
    if n_components < 2:
        raise ValueError("Too few variable features for PCA.")
    sc.pp.pca(data, n_comps=n_components, mask_var="highly_variable", random_state=seed)
    sc.pp.neighbors(data, n_neighbors=min(15, data.n_obs - 1), n_pcs=n_components, random_state=seed)
    sc.tl.umap(data, random_state=seed)
    sc.tl.leiden(data, resolution=resolution, flavor="igraph", directed=False,
                 n_iterations=2, random_state=seed, key_added="demo_cluster")
    sizes = data.obs["demo_cluster"].value_counts()
    if len(sizes) >= 2 and sizes.min() >= 2:
        sc.tl.rank_genes_groups(data, groupby="demo_cluster", method="wilcoxon",
                                use_raw=False, n_genes=20)
        ranked = sc.get.rank_genes_groups_df(data, group=None)
        ranked["interpretation"] = "Synthetic cluster description; not biological inference"
        ranked.to_csv(output / "synthetic_cluster_genes.csv", index=False)
    else:
        pd.DataFrame(columns=["group", "names", "scores", "interpretation"]).to_csv(
            output / "synthetic_cluster_genes.csv", index=False)
    data.obs.to_csv(output / "synthetic_cells.csv", index_label="barcode")
    pd.DataFrame(data.obsm["X_umap"], index=data.obs_names, columns=["UMAP1", "UMAP2"]).to_csv(
        output / "synthetic_umap.csv", index_label="barcode")
    data.var.to_csv(output / "synthetic_features.csv", index_label="gene_id")
    colors = ["demo_cluster"] + [x for x in ["simulation_population", "simulation_batch"] if x in data.obs]
    fig, axes = plt.subplots(1, len(colors), figsize=(5.2 * len(colors), 4.7), squeeze=False)
    for ax, color in zip(axes[0], colors, strict=True):
        sc.pl.umap(data, color=color, ax=ax, show=False, title=color.replace("_", " "), frameon=False)
    fig.suptitle("Synthetic single-cell demonstration | artificial features and labels", fontsize=13)
    fig.tight_layout(rect=(0, 0, 1, 0.94))
    fig.savefig(output / "synthetic_umap.png", dpi=160, bbox_inches="tight")
    plt.close(fig)
    fig, ax = plt.subplots(figsize=(7, 4.5))
    scatter = ax.scatter(qc["total_counts"], qc["n_genes_by_counts"],
                         c=qc["pct_counts_is_qc_proxy"], cmap="viridis", s=16)
    fig.colorbar(scatter, ax=ax, label="Artificial QC-proxy counts (%)")
    ax.set(xlabel="Total counts", ylabel="Detected artificial features", title="Synthetic QC demonstration")
    fig.tight_layout()
    fig.savefig(output / "synthetic_qc.png", dpi=160)
    plt.close(fig)
    provenance = {"data_origin": ORIGIN, "seed": seed, "input_sha256": input_hash,
                  "counts_layer": count_layer, "cells_before_qc": cells_before,
                  "cells_after_qc": data.n_obs, "genes_after_qc": data.n_vars,
                  "min_genes": min_genes, "max_qc_proxy_pct": max_proxy_pct,
                  "n_hvg_requested": n_hvg, "n_pcs": n_components, "leiden_resolution": resolution,
                  "python": platform.python_version()}
    for package in ("scanpy", "anndata", "numpy", "scipy", "pandas", "matplotlib", "igraph"):
        provenance[package] = version(package)
    pd.DataFrame(provenance.items(), columns=["key", "value"]).to_csv(output / "provenance.csv", index=False)
    data.uns["interpretation"] = "Synthetic software example; clusters and rankings are not biological findings."
    data.write_h5ad(output / "synthetic_processed.h5ad", compression="gzip")
    return data


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--input", type=Path, help="h5ad created by make_synthetic_data.py")
    group.add_argument("--input-dir", type=Path, help="Synthetic SoupX output directory")
    parser.add_argument("--output", type=Path, default=Path("outputs/scanpy"))
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--min-genes", type=int, default=100)
    parser.add_argument("--max-proxy-pct", type=float, default=25)
    parser.add_argument("--n-hvg", type=int, default=300)
    parser.add_argument("--resolution", type=float, default=0.5)
    args = parser.parse_args()
    data, count_layer, digest = load_input(args.input, args.input_dir, args.seed)
    result = run(data, args.output, seed=args.seed, count_layer=count_layer, input_hash=digest,
                 min_genes=args.min_genes, max_proxy_pct=args.max_proxy_pct,
                 n_hvg=args.n_hvg, resolution=args.resolution)
    print(f"Synthetic demonstration complete: {result.n_obs} cells, {result.n_vars} artificial features.")


if __name__ == "__main__":
    main()
